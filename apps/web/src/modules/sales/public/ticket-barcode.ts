export type TicketBarcode = {
  value: string;
  width: number;
  bars: readonly { x: number; width: number }[];
};

export function ticketBarcode(value: string): TicketBarcode | null {
  const normalized = value.trim().toUpperCase();
  if (!normalized || [...normalized].some((character) => !code39[character]))
    return null;
  const bars: { x: number; width: number }[] = [];
  let x = 0;
  for (const character of `*${normalized}*`) {
    const pattern = code39[character];
    if (!pattern) return null;
    for (const [index, size] of [...pattern].entries()) {
      const width = size === 'w' ? 5 : 2;
      if (index % 2 === 0) bars.push({ x, width });
      x += width;
    }
    x += 2;
  }
  return { value: normalized, width: x, bars };
}
