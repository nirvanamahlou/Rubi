import type { LucideIcon } from 'lucide-react';

export type SettingFieldType =
  'boolean' | 'file' | 'number' | 'select' | 'text' | 'time';
export type SettingTone =
  'amber' | 'blue' | 'cyan' | 'rose' | 'teal' | 'violet';

export interface SettingField {
  key: string;
  label: string;
  value: boolean | string;
  type: SettingFieldType;
  unit?: string;
  min?: number;
  max?: number;
  options?: string[];
  accept?: string;
}

export interface SettingGroup {
  id: string;
  title: string;
  icon: string;
  fields: SettingField[];
  sensitive: boolean;
  rules: string[];
}

export interface SettingModule {
  id: string;
  title: string;
  category: string;
  icon: string;
  tone: SettingTone;
  groups: SettingGroup[];
}

export type SettingIconMap = Record<string, LucideIcon>;

const n = (
  key: string,
  label: string,
  value: number,
  unit = '',
  min = 0,
  max = 1_000_000,
): SettingField => ({
  key,
  label,
  value: String(value),
  type: 'number',
  unit,
  min,
  max,
});
const s = (
  key: string,
  label: string,
  value: string,
  options: string,
): SettingField => ({
  key,
  label,
  value,
  type: 'select',
  options: options.split('|'),
});
const b = (key: string, label: string, value: boolean): SettingField => ({
  key,
  label,
  value,
  type: 'boolean',
});
const t = (
  key: string,
  label: string,
  value: string,
  type: 'text' | 'time' = 'text',
): SettingField => ({ key, label, value, type });
const f = (
  key: string,
  label: string,
  value: string,
  accept: string,
): SettingField => ({ accept, key, label, value, type: 'file' });
const g = (
  id: string,
  title: string,
  icon: string,
  fields: SettingField[],
  sensitive = false,
  rules: string[] = [],
): SettingGroup => ({ id, title, icon, fields, sensitive, rules });
const m = (
  id: string,
  title: string,
  category: string,
  icon: string,
  tone: SettingTone,
  groups: SettingGroup[],
): SettingModule => ({ id, title, category, icon, tone, groups });
